function generate() {
  const header = [
    'keyword',
    'cluster',
    'intent',
    'demand',
    'competition',
    'evidence',
    'serp_type',
    'top_competitor',
    'current_imageseo_url',
    'proposed_url',
    'priority',
    'notes'
  ].join(',');

  const rows = records.map(r => [
    `"${r.keyword}"`,
    `"${r.cluster}"`,
    `"${r.intent}"`,
    `"${r.demand}"`,
    `"${r.competition}"`,
    `"${r.evidence.replace(/"/g, '""')}"`,
    `"${r.serp_type.replace(/"/g, '""')}"`,
    `"${r.top_competitor.replace(/"/g, '""')}"`,
    `"${r.current_imageseo_url}"`,
    `"${r.proposed_url}"`,
    `"${r.priority}"`,
    `"${r.notes.replace(/"/g, '""')}"`
  ].join(','));

  fs.writeFileSync('docs/seo/keyword-opportunities-validated.csv', [header, ...rows].join('\n'), 'utf8');
  console.log('Successfully wrote docs/seo/keyword-opportunities-validated.csv');
}

generate();
